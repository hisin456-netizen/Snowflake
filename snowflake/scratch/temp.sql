2. DBMS_CRYPTO.ENCRYPT(...) => AES-256으로 암호화해서 RAW 반환
3. UTL_ENCODE.BASE64_ENCODE(...) => 암호문(바이너리)을 Base64로 인코딩. 결과는 RAW 타입(Base64 문자의 ASCII 바이트)입니다.
