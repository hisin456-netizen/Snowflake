CREATE OR REPLACE PROCEDURE DW.DW_META.SP_DW_SP_LOG_U("P_EXEC_ID" VARCHAR, "P_EXEC_STEP" VARCHAR, "P_STATUS" VARCHAR, "P_COPY_QUERY_ID" VARCHAR, "P_COPY_FLAG" NUMBER(38,0), "P_COPY_FILE_CNT" NUMBER(38,0), "P_COPY_LOADED_CNT" NUMBER(38,0), "P_RAW_DELETE_CNT" NUMBER(38,0), "P_RAW_INSERT_CNT" NUMBER(38,0), "P_MERGE_QUERY_ID" VARCHAR, "P_RAW_MERGE_INSERT_CNT" NUMBER(38,0), "P_RAW_MERGE_UPDATE_CNT" NUMBER(38,0), "P_RAW_MERGE_DELETE_CNT" NUMBER(38,0), "P_RAW_PRUNING_DELETE_CNT" NUMBER(38,0), "P_ERROR_CODE" VARCHAR, "P_ERROR_STATE" VARCHAR, "P_ERROR_MSG" VARCHAR, "P_REMARK" VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS '
BEGIN
    UPDATE DW.DW_META.DW_SP_LOG
       SET EXEC_STEP              = :P_EXEC_STEP,
           STATUS                 = :P_STATUS,
           END_TS                 = CURRENT_TIMESTAMP(),
           ELAPSED_SEC            = DATEDIFF(''millisecond'', START_TS, CURRENT_TIMESTAMP()) / 1000,
           COPY_QUERY_ID          = :P_COPY_QUERY_ID,
           COPY_FLAG              = :P_COPY_FLAG,
           COPY_FILE_CNT          = :P_COPY_FILE_CNT,
           COPY_LOADED_CNT        = :P_COPY_LOADED_CNT,
           RAW_DELETE_CNT         = :P_RAW_DELETE_CNT,
           RAW_INSERT_CNT         = :P_RAW_INSERT_CNT,
           MERGE_QUERY_ID         = :P_MERGE_QUERY_ID,
           RAW_MERGE_INSERT_CNT   = :P_RAW_MERGE_INSERT_CNT,
           RAW_MERGE_UPDATE_CNT   = :P_RAW_MERGE_UPDATE_CNT,
           RAW_MERGE_DELETE_CNT   = :P_RAW_MERGE_DELETE_CNT,
           RAW_PRUNING_DELETE_CNT = :P_RAW_PRUNING_DELETE_CNT,
           ERROR_CODE             = :P_ERROR_CODE,
           ERROR_STATE            = :P_ERROR_STATE,
           ERROR_MSG              = :P_ERROR_MSG,
           REMARK                 = :P_REMARK
     WHERE EXEC_ID = :P_EXEC_ID;
EXCEPTION
    WHEN OTHER THEN
        -- 로그 실패가 본 적재를 중단시키지 않도록 오류 문자열만 반환
        RETURN ''LOG_ERROR: '' || SQLERRM;
END;
';