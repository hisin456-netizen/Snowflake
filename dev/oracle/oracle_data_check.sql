-- 실행: 문장 하나씩 커서를 두고 Ctrl+Enter
-- 바인드 변수(:BASE_DATE)는 DBeaver 가 값 입력창을 띄운다.
--   SH_COSTS     : YYYYMMDD (예: 20261110)
--   SH_COSTS_MM  : YYYYMM   (예: 202611)
--   SH_COSTS_YYYY: YYYY     (예: 2026)
